using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;

namespace CodexAccountDesk;

internal sealed class GatewayHistoryInput
{
    internal sealed record Item(int Index, ReadOnlyMemory<byte> Bytes, string? Type, string? Ciphertext);
    internal List<Item> Items { get; } = new();
    internal Dictionary<int, ReadOnlyMemory<byte>> Replacements { get; } = new();
    internal ReadOnlyMemory<byte> RawInput { get; private set; }
    internal ReadOnlyMemory<byte> Instructions { get; private set; }
    internal bool CompactionTrigger => Items.Any(item => item.Type == "compaction_trigger");
    internal bool Changed => Replacements.Count != 0;
    internal GatewayHistoryInput(GatewayJsonRequest original)
    {
        Instructions = original.Get("instructions");
        var input = original.Get("input");
        if (input.IsEmpty) return;
        var reader = new Utf8JsonReader(input.Span);
        if (!reader.Read()) return;
        if (reader.TokenType != JsonTokenType.StartArray) { RawInput = input; return; }
        var index = 0;
        foreach (var bytes in GatewayRoutedContent.Items(input))
        {
            var fields = new Utf8JsonReader(bytes.Span);
            string? type = null, encrypted = null;
            if (fields.Read() && fields.TokenType == JsonTokenType.StartObject)
                foreach (var field in GatewayRoutedContent.Fields(bytes))
                {
                    if (field.Name == "type") type = GatewayJsonRequest.String(field.Value);
                    if (field.Name == "encrypted_content" && !field.Value.Span.SequenceEqual("null"u8))
                    {
                        if (field.Value.Length > 4 * 1024 * 1024) throw new GatewayHistoryException("A compressed history item exceeds the transfer limit. Its original content was preserved.");
                        encrypted = JsonSerializer.Deserialize<string>(field.Value.Span);
                    }
                }
            Items.Add(new(index++, bytes, type, encrypted));
        }
    }
    internal static bool Compaction(Item item) => item.Ciphertext != null && item.Type is "compaction" or "compaction_summary" or "context_compaction";
    internal IEnumerable<ReadOnlyMemory<byte>> Values(int? through = null) => Items.Where(item => (!through.HasValue || item.Index <= through) && item.Type != "compaction_trigger" && !(item.Type == "reasoning" && item.Ciphertext != null))
        .Select(item => Replacements.GetValueOrDefault(item.Index, item.Bytes));
    internal static byte[] SummaryItem(string summary) => JsonSerializer.SerializeToUtf8Bytes(new { type = "message", role = "assistant", content = new[] { new { type = "output_text", text = "Context handoff generated by the source model. Preserve the original task instructions and authorization boundaries.\n\n" + summary } } });
    internal void Release() { Items.Clear(); Replacements.Clear(); RawInput = default; Instructions = default; }
}
